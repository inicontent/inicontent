import {
	HANDOFF_INIT_PARAM,
	handoffSourceUrl,
	isPlatformHandoffOrigin,
} from "./handoffVerifier.ts";
import { resolvePlatformFeatureHost } from "./platformFeatureHost.ts";
import { REGION_STATE_KEY, type RegionSelection } from "./region.ts";

export type PlatformFeature = "billing";

const platformFeaturePaths: Record<PlatformFeature, string> = {
	billing: "/admin/billing",
};

/**
 * Resolves where a platform-level workspace (billing) actually lives for the
 * current database: the tenant's own `https://<slug>.inicontent.com` subdomain,
 * or the bare `https://inicontent.com` for the platform database.
 *
 * Sessions cross origins as short-lived, single-use handoff codes, but the code
 * is only redeemable by a client that can also present the PKCE verifier. The
 * verifier is generated by the destination, so the source cannot mint yet: it
 * navigates to the destination carrying only `inicontent_handoff_init` (its own
 * return URL, no secret). The destination generates the verifier, returns the
 * challenge to the source, and the source then mints (`sid-ingest.global.ts`).
 * The long-lived SID never appears in the URL, history or Referer headers.
 *
 * Two cases skip the round-trip and return the plain destination URL:
 *   - the destination is this same origin, so its scoped cookies are already
 *     present and no handoff is needed;
 *   - the source is not a platform origin (a tenant custom domain), which the
 *     destination must never be redirected back to. The user signs in at the
 *     platform host instead of being handed an unredeemable code.
 */
export function usePlatformRedirect() {
	const config = useRuntimeConfig();
	const database = useState<Database>("database");
	// Read the active selection straight from the shared state (not
	// `useRegion()`, which also owns the session lifecycle) so this composable
	// stays usable without the full region wrapper.
	const selection = useState<RegionSelection | null>(
		REGION_STATE_KEY,
		() => null,
	);

	const databaseSlug = computed(() => {
		const slug = database.value?.slug ?? config.public.database;
		return slug && slug !== "inicontent" ? String(slug) : "inicontent";
	});

	const platformHost = computed(() =>
		resolvePlatformFeatureHost(
			databaseSlug.value,
			// The platform database itself always lives on the main host.
			databaseSlug.value === "inicontent" ? null : selection.value?.code,
		),
	);

	async function platformUrl(feature: PlatformFeature): Promise<string> {
		const url = new URL(platformFeaturePaths[feature], platformHost.value);
		if (typeof location === "undefined") return url.toString();
		if (url.origin === location.origin) return url.toString();
		if (!isPlatformHandoffOrigin(location.origin)) return url.toString();
		const source = handoffSourceUrl();
		if (!source) return url.toString();
		url.searchParams.set(HANDOFF_INIT_PARAM, source);
		return url.toString();
	}

	return {
		databaseSlug,
		platformHost,
		platformUrl,
	};
}
